"""Validate/quarantine a GitHub issue attachment. No compiler or signing key.

The workflow executes only this trusted base-repository script, never contributed
code. An attachment passing this gate still needs maintainer/gameplay review.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
import urllib.request
from urllib.parse import urlsplit
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'packaging/macos/native'))
import community_catalog as c

MAX_UPLOAD=8*1024*1024
ATTACHMENT=re.compile(r'https://github\.com/user-attachments/files/[0-9]+/GOW3-[0-9a-f]{20}\.txt(?=$|[\s)`>])')
REDIRECT_HOSTS={'github.com','github-production-user-asset-6210df.s3.amazonaws.com',
                'github-production-repository-file-5c1aeb.s3.amazonaws.com'}

def attachment_url(body):
    if not isinstance(body,str) or len(body)>100_000:
        raise ValueError('Issue body bounds')
    found=set(ATTACHMENT.findall(body))
    if len(found)!=1:
        raise ValueError('Attach exactly one GOW3 catalogue .txt generated by the launcher')
    url=next(iter(found)); parsed=urlsplit(url)
    if parsed.netloc!='github.com' or parsed.query or parsed.fragment or not ATTACHMENT.fullmatch(url):
        raise ValueError('Attachment URL rejected')
    return url

class RestrictedRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self,request,fp,code,msg,headers,newurl):
        parsed=urlsplit(newurl)
        if parsed.scheme!='https' or parsed.hostname not in REDIRECT_HOSTS or parsed.username or parsed.password or parsed.port not in (None,443):
            raise ValueError('Attachment redirect rejected')
        return super().redirect_request(request,fp,code,msg,headers,newurl)

def download(url,path):
    if not ATTACHMENT.fullmatch(url):
        raise ValueError('Attachment URL rejected')
    opener=urllib.request.build_opener(RestrictedRedirect())
    with opener.open(urllib.request.Request(url,headers={'User-Agent':'GOW3-Catalogue-Review/1'}),timeout=15) as response:
        length=response.headers.get('Content-Length')
        if response.status!=200 or (length and int(length)>MAX_UPLOAD):
            raise ValueError('Attachment download bounds')
        data=response.read(MAX_UPLOAD+1)
    if len(data)>MAX_UPLOAD:
        raise ValueError('Attachment download bounds')
    Path(path).write_bytes(data)

def validate(path):
    if Path(path).is_symlink() or Path(path).stat().st_size>MAX_UPLOAD:
        raise ValueError('Contribution file bounds')
    rows=c.load(path)
    if not rows or {r['abi'] for r in rows.values()}!={c.EARLY_DEPTH_ABI}:
        raise ValueError('Contribution renderer ABI mismatch')
    for row in rows.values():
        if row['key_size']!=352:
            raise ValueError('Contribution pipeline layout')
        if row['kind']=='shader' and (row['runtime_size']!=288 or len(row['specialization'])<600):
            raise ValueError('Contribution shader layout')
        if row['kind']=='pipeline' and any(stage not in rows for stage in row['stages'].values()):
            raise ValueError('Contribution shader dependency missing')
    return rows

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--event',type=Path)
    parser.add_argument('--file',type=Path)
    parser.add_argument('--output',required=True,type=Path)
    args=parser.parse_args();args.output.mkdir(parents=True,exist_ok=True)
    if args.event:
        if args.event.stat().st_size>1024*1024:raise ValueError('Event bounds')
        event=c.strict_json(args.event.read_bytes())
        url=attachment_url(event['issue']['body'])
        path=args.output/'incoming.txt';download(url,path)
    elif args.file:path=args.file
    else:raise ValueError('Expected issue event or file')
    rows=validate(path)
    result=c.save(args.output/'validated-catalogue.jsonl',rows)
    result.update(schema_valid=True,review_required=True,published=False)
    (args.output/'review.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps(result))

if __name__=='__main__':main()
